function escapePhrase(phrase) {
  return phrase.replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replace(/\s+/g, "\\s+");
}

export function buildGeoRegex(phrases) {
  const parts = [...phrases]
    .map((p) => p.trim())
    .filter((p) => p.length >= 3)
    .sort((a, b) => b.length - a.length)
    .map((p) => `\\b${escapePhrase(p)}\\b`);
  return new RegExp(parts.join("|"), "i");
}

