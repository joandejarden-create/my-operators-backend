export function classifyCell(value) {
  if (value == null || value === "") return "BLANK";
  if (Array.isArray(value)) {
    if (!value.length) return "BLANK";
    if (value.some((x) => UNRESOLVED_MARKERS.has(String(x)))) return "UNRESOLVED";
    return "ACTUAL";
  }
  const s = String(value).trim();
  if (UNRESOLVED_MARKERS.has(s)) return "UNRESOLVED";
  if (/^No (sufficiently|verified|official)/i.test(s)) return "UNRESOLVED";
  return "ACTUAL";
}
