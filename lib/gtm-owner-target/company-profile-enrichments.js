/**
 * @param {string} ownerName
 * @returns {CompanyProfileEnrichment | null}
 */
export function findCompanyProfileEnrichment(ownerName) {
  const norm = String(ownerName || "")
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ");
  if (!norm) return null;

  for (const profile of COMPANY_PROFILE_ENRICHMENTS) {
    const names = [
      profile.company?.name,
      ...(profile.ownerTarget?.preferredNames || []),
    ].filter(Boolean);
    for (const name of names) {
      const nameNorm = name.toLowerCase().replace(/[^a-z0-9]+/g, " ");
      if (norm === nameNorm || norm.includes(nameNorm) || nameNorm.includes(norm)) {
        return profile;
      }
    }
  }
  return null;
}
