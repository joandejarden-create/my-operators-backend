export function applyBonairePlaceReviewCorrection(point) {
  const fix = BONAIRE_GOOGLE_PLACE_REVIEW_CORRECTIONS[point.name];
  if (!fix) return point;
  const merged = { ...point, ...fix };
  if (fix.manuallyVerified) {
    merged.manuallyVerified = true;
    merged.dataConfidence = fix.dataConfidence || "High";
  }
  merged.notes = `${point.notes || ""} ${REVIEW_TAG}`.trim();
  return merged;
}

export function applyBonairePlaceReviewCorrections(points) {
  return points.map(applyBonairePlaceReviewCorrection);
}
