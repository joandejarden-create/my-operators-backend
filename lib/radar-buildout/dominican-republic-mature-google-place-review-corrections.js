export function applyDominicanRepublicMaturePlaceReviewCorrection(point) {
  const fix = DOMINICAN_REPUBLIC_MATURE_GOOGLE_PLACE_REVIEW_CORRECTIONS[point.name];
  if (!fix) return point;
  const merged = { ...point, ...fix };
  if (fix.manuallyVerified) {
    merged.manuallyVerified = true;
    merged.dataConfidence = fix.dataConfidence || "High";
  }
  merged.notes = `${point.notes || ""} ${REVIEW_TAG}`.trim();
  return merged;
}

export function applyDominicanRepublicMaturePlaceReviewCorrections(points) {
  return points.map(applyDominicanRepublicMaturePlaceReviewCorrection);
}
