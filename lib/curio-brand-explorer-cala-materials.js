/** All rows to overlay onto Curio presentation fixtures. */
export function getCurioCalaMaterialRows() {
  return [
    ...CURIO_CALA_MATERIALS_MISC_ROWS,
    ...CURIO_CALA_GALLERY_ROWS,
    ...CURIO_CALA_CASE_STUDY_ROWS,
    ...CURIO_CALA_FOOTPRINT_OPENING_ROWS,
    ...CURIO_CALA_FOOTPRINT_MOMENTUM_ROWS,
  ];
}

/**
 * Replace matching slotKeys in a presentation fixture row array.
 * @param {object[]} templateRows
 * @returns {object[]}
 */
export function overlayCurioCalaMaterials(templateRows) {
  const overlays = new Map();
  for (const row of getCurioCalaMaterialRows()) {
    if (row.slotKey === "materials.file") {
      continue;
    }
    if (row.slotKey === "materials.caseStudy" || row.slotKey === "footprint.openings" || row.slotKey === "footprint.momentum") {
      continue;
    }
    overlays.set(row.slotKey, row);
  }

  const fileOverlays = CURIO_CALA_MATERIALS_MISC_ROWS.filter((r) => r.slotKey === "materials.file");

  const caseStudies = CURIO_CALA_CASE_STUDY_ROWS;
  const openings = CURIO_CALA_FOOTPRINT_OPENING_ROWS;
  const momentum = CURIO_CALA_FOOTPRINT_MOMENTUM_ROWS;

  const out = [];
  let caseIdx = 0;
  let openingIdx = 0;
  let momentumIdx = 0;

  for (const row of templateRows) {
    const sk = String(row.slotKey || "");
    if (sk === "materials.file") {
      const hit = fileOverlays.find((f) => f.sort === row.sort);
      if (hit) {
        out.push({ ...row, ...hit });
        continue;
      }
    }
    if (sk === "materials.caseStudy") {
      if (caseIdx < caseStudies.length) out.push({ ...caseStudies[caseIdx++] });
      continue;
    }
    if (sk === "footprint.openings") {
      if (openingIdx < openings.length) out.push({ ...openings[openingIdx++] });
      continue;
    }
    if (sk === "footprint.momentum") {
      if (momentumIdx < momentum.length) out.push({ ...momentum[momentumIdx++] });
      continue;
    }
    if (overlays.has(sk)) {
      out.push({ ...row, ...overlays.get(sk) });
      continue;
    }
    out.push({ ...row });
  }

  return out;
}
