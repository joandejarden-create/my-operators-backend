/** Flatten include+exclude into certification ledger rows. */
export function buildPeerCertificationLedgerV1() {
  const rows = [];
  for (const ps of Object.values(BRAND_PORTFOLIO_PEER_SETS_V1)) {
    for (const p of ps.included) {
      rows.push({
        subjectPropertyId: ps.propertyId,
        lensId: ps.lensId,
        peerEntityId: p.canonicalEntityId,
        canonicalName: p.peerHotel,
        brand: p.brand,
        parentCompany: p.parentCompany,
        loyaltyEcosystem: p.ecosystem,
        market: p.market,
        submarket: p.submarket,
        openStatus: p.openStatus,
        affiliationStatus: p.affiliationStatus,
        marketRelevance: p.marketRelevance,
        inclusionLevel: p.expansionLevel,
        inclusionDecision: "INCLUDE",
        evidenceSource: p.evidenceSource,
        verificationTimestamp: VERIFICATION_TIMESTAMP,
        peerSetId: ps.peerSetId,
        peerSetVersion: ps.peerSetVersion,
      });
    }
    for (const e of ps.excluded) {
      rows.push({
        subjectPropertyId: ps.propertyId,
        lensId: ps.lensId,
        peerEntityId: null,
        canonicalName: e.candidate,
        brand: e.brand,
        parentCompany: null,
        loyaltyEcosystem: null,
        market: null,
        submarket: null,
        openStatus: null,
        affiliationStatus: null,
        marketRelevance: null,
        inclusionLevel: null,
        inclusionDecision: "EXCLUDE",
        evidenceSource: e.exclusionReason,
        verificationTimestamp: VERIFICATION_TIMESTAMP,
        peerSetId: ps.peerSetId,
        peerSetVersion: ps.peerSetVersion,
        priorProposal: e.priorProposal || null,
      });
    }
  }
  return {
    ledgerVersion: PEER_CERTIFICATION_LEDGER_VERSION,
    verificationTimestamp: VERIFICATION_TIMESTAMP,
    gate: "LOYALTY_ECOSYSTEM_PEER_SET_INTEGRITY",
    rowCount: rows.length,
    rows,
  };
}
