    peerSetId: `bps_${propertyId}_${lensId}_certified_v1`,
    peerSetVersion: PEER_SET_VERSION,
    universeContract: "ADP_LOYALTY_ECOSYSTEM_PEER_UNIVERSE_V1",
    propertyId,
    subjectName,
    lensId,
    lensLabel,
    ecosystem,
    expansionLevelUsed,
    included: Object.freeze(included.map(peer)),
    excluded: Object.freeze(excluded.map((e) => Object.freeze(e))),
    peerCountExcludingSubject: included.length,
    adequacy,
    certifiedAt: VERIFICATION_TIMESTAMP,
    founderVerificationPass: true,
    notes: Object.freeze(notes || []),
