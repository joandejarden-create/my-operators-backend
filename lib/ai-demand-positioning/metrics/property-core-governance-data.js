export function roleOverridesForProperty(propertyId) {
  return PROPERTY_ROLE_OVERRIDES[propertyId] || null;
}

export function stabilizedCoreIdsForProperty(propertyId, intent) {
  return [...(PROPERTY_STABILIZED_CORE_IDS[propertyId]?.[intent] || [])];
}

export function isGovernedNonWaterstoneProperty(propertyId) {
  return GOVERNED_NON_WATERSTONE_PROPERTIES.includes(propertyId);
}

export function propertyCoreGovernanceReady(propertyId) {
  const cores = PROPERTY_STABILIZED_CORE_IDS[propertyId];
  if (!cores) return false;
  return Object.values(cores).some((ids) => ids.length >= MIN_CORE_HOTELS_PRODUCTION);
}
