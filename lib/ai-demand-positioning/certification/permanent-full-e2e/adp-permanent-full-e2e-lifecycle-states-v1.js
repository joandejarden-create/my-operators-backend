/**
 * ADP permanent Full E2E certification lifecycle states.
 * Downstream stages cannot override a failed upstream gate.
 */

export const ADP_PERMANENT_FULL_E2E_CERTIFICATION_CONTRACT_V1 =
  "ADP_PERMANENT_FULL_E2E_CERTIFICATION_CONTRACT_V1";

export const CERTIFICATION_LIFECYCLE_STATES = Object.freeze({
  RESEARCH_COMPLETE: "RESEARCH_COMPLETE",
  EVIDENCE_VALIDATED: "EVIDENCE_VALIDATED",
  ELIGIBILITY_CERTIFIED: "ELIGIBILITY_CERTIFIED",
  METRICS_RECONCILED: "METRICS_RECONCILED",
  EVIDENCE_CERTIFIED: "EVIDENCE_CERTIFIED",
  PERSISTENCE_VERIFIED: "PERSISTENCE_VERIFIED",
  PACKAGE_CERTIFIED: "PACKAGE_CERTIFIED",
  RENDER_CERTIFIED: "RENDER_CERTIFIED",
  APPROVED_FOR_PUBLICATION: "APPROVED_FOR_PUBLICATION",
  PUBLISHED: "PUBLISHED",
  CUSTOMER_READY: "CUSTOMER_READY",
});

export const CERTIFICATION_FAILURE_STATES = Object.freeze({
  EVIDENCE_INCOMPLETE: "EVIDENCE_INCOMPLETE",
  ELIGIBILITY_MISMATCH: "ELIGIBILITY_MISMATCH",
  METRIC_RECONCILIATION_FAILED: "METRIC_RECONCILIATION_FAILED",
  PERSISTENCE_INCOMPLETE: "PERSISTENCE_INCOMPLETE",
  PACKAGE_INTEGRITY_FAILED: "PACKAGE_INTEGRITY_FAILED",
  RENDER_VALIDATION_FAILED: "RENDER_VALIDATION_FAILED",
  PRODUCTION_PARITY_FAILED: "PRODUCTION_PARITY_FAILED",
});

/** Ordered success path — each step requires all prior success states. */
export const CERTIFICATION_SUCCESS_ORDER = Object.freeze([
  CERTIFICATION_LIFECYCLE_STATES.RESEARCH_COMPLETE,
  CERTIFICATION_LIFECYCLE_STATES.EVIDENCE_VALIDATED,
  CERTIFICATION_LIFECYCLE_STATES.ELIGIBILITY_CERTIFIED,
  CERTIFICATION_LIFECYCLE_STATES.METRICS_RECONCILED,
  CERTIFICATION_LIFECYCLE_STATES.EVIDENCE_CERTIFIED,
  CERTIFICATION_LIFECYCLE_STATES.PERSISTENCE_VERIFIED,
  CERTIFICATION_LIFECYCLE_STATES.PACKAGE_CERTIFIED,
  CERTIFICATION_LIFECYCLE_STATES.RENDER_CERTIFIED,
  CERTIFICATION_LIFECYCLE_STATES.APPROVED_FOR_PUBLICATION,
  CERTIFICATION_LIFECYCLE_STATES.PUBLISHED,
  CERTIFICATION_LIFECYCLE_STATES.CUSTOMER_READY,
]);

export function canAdvanceTo(currentStates = [], nextState) {
  const idx = CERTIFICATION_SUCCESS_ORDER.indexOf(nextState);
  if (idx < 0) return { ok: false, reason: "UNKNOWN_TARGET_STATE" };
  const required = CERTIFICATION_SUCCESS_ORDER.slice(0, idx);
  const have = new Set(currentStates || []);
  const missing = required.filter((s) => !have.has(s));
  return {
    ok: missing.length === 0,
    missing,
    reason: missing.length ? "UPSTREAM_GATE_INCOMPLETE" : null,
  };
}

export function describeLifecycleContract() {
  return {
    contract: ADP_PERMANENT_FULL_E2E_CERTIFICATION_CONTRACT_V1,
    successStates: CERTIFICATION_LIFECYCLE_STATES,
    failureStates: CERTIFICATION_FAILURE_STATES,
    order: CERTIFICATION_SUCCESS_ORDER,
    rule: "No stage may be skipped; downstream cannot override failed upstream.",
  };
}
