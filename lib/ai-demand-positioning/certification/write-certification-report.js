/**
 * Write ADP_CERTIFICATION_REPORT.md + .json under reports/ai-demand-positioning/certification/<propertyId>/
 */

import { mkdirSync, writeFileSync } from "fs";
import { join } from "path";

function mdEscape(s) {
  return String(s ?? "").replace(/\|/g, "\\|");
}

export function certificationReportPaths(propertyId, root = process.cwd()) {
  const dir = join(root, "reports/ai-demand-positioning/certification", propertyId);
  return {
    dir,
    md: join(dir, "ADP_CERTIFICATION_REPORT.md"),
    json: join(dir, "ADP_CERTIFICATION_REPORT.json"),
  };
}

export function renderCertificationMarkdown(report) {
  const lines = [];
  lines.push(`# ADP Property Certification Report`);
  lines.push(``);
  lines.push(`| Field | Value |`);
  lines.push(`| --- | --- |`);
  lines.push(`| Property | ${mdEscape(report.propertyName)} (\`${report.propertyId}\`) |`);
  lines.push(`| Status | **${report.status}** |`);
  lines.push(`| Certified at | ${report.certifiedAt} |`);
  lines.push(`| Audit version | ${report.certificationVersion} |`);
  lines.push(`| Measurement contract | ${report.measurementContractVersion} |`);
  lines.push(`| Contract hash | \`${String(report.measurementContractHash || "").slice(0, 16)}…\` |`);
  lines.push(`| Period | \`${report.periodId || "—"}\` |`);
  lines.push(
    `| Classification | ${report.classification?.classification || "—"} (${report.classification?.inOfficialFour ? "official four" : "standalone / other"}) |`
  );
  lines.push(`| Material fails | ${report.materialFailCount} |`);
  lines.push(`| Disclosures | ${report.disclosureCount} |`);
  lines.push(``);

  lines.push(`## Gate results`);
  lines.push(``);
  lines.push(`| Gate | Status | Material | Issue class | Summary |`);
  lines.push(`| --- | --- | --- | --- | --- |`);
  for (const g of report.gates || []) {
    lines.push(
      `| \`${g.gateId}\` | ${g.status} | ${g.material ? "yes" : "no"} | ${g.issueClass || "—"} | ${mdEscape(g.summary)} |`
    );
  }
  lines.push(``);

  const metrics = report.sections?.metricReconciliation || [];
  if (metrics.length) {
    lines.push(`## Metric reconciliation`);
    lines.push(``);
    lines.push(`| Metric | Published | Independent | Match |`);
    lines.push(`| --- | --- | --- | --- |`);
    for (const m of metrics) {
      lines.push(
        `| ${mdEscape(m.metric)} | ${m.published ?? "—"} | ${m.independent ?? "—"} | ${m.match ? "PASS" : "FAIL"} |`
      );
    }
    lines.push(``);
  }

  const openai = report.sections?.openaiFalseNegatives;
  if (openai) {
    lines.push(`## OpenAI false-negative audit`);
    lines.push(``);
    lines.push(`- Comparable OpenAI observations: ${openai.openaiComparable}`);
    lines.push(`- Stored misses: ${openai.openaiMisses} (presence ${openai.openaiPresenceRate}%)`);
    lines.push(`- TRUE_MISS: ${openai.trueMiss}`);
    lines.push(`- MATCHING_FALSE_NEGATIVE / PARSER_DEFECT: ${openai.matchingFalseNegative} (parserDefect=${openai.parserDefect})`);
    lines.push(`- AMBIGUOUS: ${openai.ambiguous}`);
    lines.push(`- FN share of misses: ${openai.falseNegativeShareOfMisses}%`);
    lines.push(``);
  }

  const entities = report.sections?.entities;
  if (entities) {
    lines.push(`## Entity audit`);
    lines.push(``);
    lines.push(
      `- Mentions: ${entities.totalMentions}; ok=${entities.ok}; junk=${entities.junk}; unresolved=${entities.unresolved}`
    );
    if (entities.sampleJunk?.length) {
      lines.push(`- Sample junk: ${entities.sampleJunk.map((j) => j.rawName).join("; ")}`);
    }
    lines.push(``);
  }

  const anomalies = report.sections?.anomalies || [];
  if (anomalies.length) {
    lines.push(`## Anomalies`);
    lines.push(``);
    for (const a of anomalies) {
      lines.push(`- **${a.severity}** \`${a.rule}\``);
    }
    lines.push(``);
  }

  const disclosures = (report.gates || []).flatMap((g) =>
    (g.disclosures || []).map((d) => ({ gateId: g.gateId, d }))
  );
  if (disclosures.length) {
    lines.push(`## Disclosures`);
    lines.push(``);
    for (const { gateId, d } of disclosures) {
      lines.push(`- [\`${gateId}\`] ${d}`);
    }
    lines.push(``);
  }

  lines.push(`## Internal status (customer UI unchanged)`);
  lines.push(``);
  lines.push(`- \`status\`: ${report.status}`);
  lines.push(`- \`certificationDate\`: ${report.certifiedAt}`);
  lines.push(`- \`measurementContract\`: ${report.measurementContractVersion}`);
  lines.push(`- \`auditVersion\`: ${report.certificationVersion}`);
  lines.push(``);
  lines.push(`---`);
  lines.push(`*Generated by \`npm run audit:adp-property\` — read-only; no LLM calls; methodology not auto-changed.*`);
  lines.push(``);
  return lines.join("\n");
}

export function writeCertificationReport(report, root = process.cwd()) {
  const paths = certificationReportPaths(report.propertyId, root);
  mkdirSync(paths.dir, { recursive: true });
  writeFileSync(paths.json, JSON.stringify(report, null, 2), "utf8");
  writeFileSync(paths.md, renderCertificationMarkdown(report), "utf8");
  return paths;
}
