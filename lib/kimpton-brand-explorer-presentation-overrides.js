export function overrideKey(slotKey, title = "", sort = null) {
  const t = String(title || "").trim();
  if (t) return `${slotKey}::${t}`;
  if (sort != null && sort !== "") return `${slotKey}@${sort}`;
  return slotKey;
}

export function applyKimptonGlobalReplacements(text) {
  if (typeof text !== "string") return text;
  let s = text;
  for (const [pattern, replacement] of KIMPTON_GLOBAL_REPLACEMENTS) {
    s = s.replace(pattern, replacement);
  }
  return s;
}
