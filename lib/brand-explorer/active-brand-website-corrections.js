export function normalizeBrandWebsiteUrl(raw) {
  const v = String(raw ?? "").trim();
  if (!v) return "";
  let url;
  try {
    url = new URL(v.includes("://") ? v : `https://${v}`);
  } catch {
    return v;
  }
  if (url.protocol !== "https:" && url.protocol !== "http:") return v;
  url.protocol = "https:";
  if (url.hostname.toLowerCase().startsWith("www.")) {
    url.hostname = url.hostname.slice(4);
  }
  let out = url.toString();
  if (out.endsWith("/") && url.pathname !== "/") out = out.replace(/\/+$/, "");
  return out;
}

export function isParentCompanyHomepage(url, parentCompany = "", brandName = "") {
  const normalized = normalizeBrandWebsiteUrl(url).toLowerCase();
  const parent = String(parentCompany || "").toLowerCase();
  const brand = String(brandName || "").toLowerCase().trim();
  const generic = [
    "https://marriott.com",
    "https://marriott.com/",
    "https://ihg.com",
    "https://ihg.com/",
    "https://hyatt.com",
    "https://hyatt.com/",
    "https://accor.com",
    "https://accor.com/",
    "https://wyndham.com",
    "https://wyndham.com/",
    "https://wyndhamhotels.com",
    "https://wyndhamhotels.com/",
    "https://minorhotels.com",
    "https://minorhotels.com/",
    "https://hilton.com",
    "https://hilton.com/",
    "https://choicehotels.com",
    "https://choicehotels.com/",
    "https://group.accor.com",
    "https://group.accor.com/",
  ];
  if (generic.includes(normalized)) {
    // Flagship portfolio brands may legitimately use the parent root only when
    // the Brand Basics name is exactly the parent flagship (e.g. "Hyatt").
    if (
      (brand === "hyatt" && /hyatt\.com\/?$/.test(normalized)) ||
      (brand === "wyndham" && /wyndham(hotels)?\.com\/?$/.test(normalized))
    ) {
      return false;
    }
    return true;
  }
  if (/minorhotels\.com\/?$/i.test(normalized) && parent.includes("nh")) return true;
  return false;
}

/**
 * Customer-facing Brand Website label — must remain brand-distinctive.
 * Never reduce brand-specific paths (marriott.com/en-us/brands/…) to bare parent host.
 */
export function brandWebsiteDisplayLabel(raw) {
  const v = String(raw ?? "").trim();
  if (!v) return "";
  try {
    const url = new URL(v.includes("://") ? v : `https://${v}`);
    const host = url.hostname.toLowerCase().replace(/^www\./, "");
    const path = (url.pathname || "").replace(/\/+$/, "");
    if (!host) return "Official brand website";
    if (!path || path === "/") return host;
    let label = `${host}${path}`;
    if (label.length > 64) {
      const parts = path.split("/").filter(Boolean);
      const tail = parts.slice(-2).join("/");
      label = `${host}/…/${tail}`;
    }
    return label;
  } catch {
    return "Official brand website";
  }
}
