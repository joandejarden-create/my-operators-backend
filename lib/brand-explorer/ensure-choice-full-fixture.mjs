/**
 * Write brand-explorer-presentation-{slug}-full.json when missing (Tier 1 or stub profile).
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { buildCompletePresentationRows } from "../../scripts/lib/choice-explorer-complete-rows.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..", "..");
const FIXTURES = path.join(ROOT, "fixtures");

/**
 * @param {{ airtableName: string, slug: string, profileName: string, fullFixture: string|null }} brand
 * @returns {{ created: boolean, path: string, rowCount: number }}
 */
export function ensureChoiceFullFixture(brand) {
  const rel = brand.fullFixture || `fixtures/brand-explorer-presentation-${brand.slug}-full.json`;
  const outPath = path.join(ROOT, rel);

  if (fs.existsSync(outPath)) {
    const existing = JSON.parse(fs.readFileSync(outPath, "utf8"));
    const rows = existing.rows || [];
    return { created: false, path: outPath, rowCount: rows.length };
  }

  const rows = buildCompletePresentationRows(brand.airtableName);
  const fixture = {
    targetBrandBasicsName: brand.airtableName,
    instructions: `Generated by ensure-choice-full-fixture for ${brand.profileName}`,
    rows,
  };

  fs.mkdirSync(FIXTURES, { recursive: true });
  fs.writeFileSync(outPath, `${JSON.stringify(fixture, null, 2)}\n`, "utf8");

  return { created: true, path: outPath, rowCount: rows.length };
}
