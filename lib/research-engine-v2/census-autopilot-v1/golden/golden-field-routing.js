function amenityRoute(label) {
  return {
    best: "official_amenity_inventory_explicit",
    second: "official_property_page_mention",
    fallback: "Unknown (never infer No from silence)",
    normalization: "Yes|Unknown|N/A — never silent-No",
    confidence: "Medium when Yes",
    stop_rule: `stop_on_explicit_${label.replace(/\W+/g, "_").toLowerCase()}_or_unknown`,
    escalation: "accept_unknown",
  };
}

function pick(obj, keys) {
  const o = {};
  for (const k of keys) o[k] = obj[k];
  return o;
}

export function buildGoldenFieldRoutingPlan() {
  const rows = [];
  for (const entry of GOLDEN_FIELD_REGISTRY) {
    const r = ROUTES[entry.field] || {
      best: DEFAULT_LADDER.best,
      second: DEFAULT_LADDER.second,
      fallback: DEFAULT_LADDER.fallback,
      normalization: "as_documented_in_schema",
      confidence: "Medium",
      stop_rule: DEFAULT_LADDER.stop_rule,
      escalation: DEFAULT_LADDER.escalation,
    };
    rows.push({
      field: entry.field,
      track: entry.track,
      group: entry.group,
      applicability: entry.applicability,
      weight_band: entry.weight_band,
      best_source: r.best,
      second_source: r.second,
      fallback: r.fallback,
      normalization: r.normalization,
      confidence_rule: r.confidence,
      stop_rule: r.stop_rule,
      escalation_path: r.escalation,
      cvent_allowed_as_production: false,
      legacy_allowed_as_production: false,
    });
  }
  return {
    version: "golden-field-routing-v1.2",
    fields: rows,
  };
}
