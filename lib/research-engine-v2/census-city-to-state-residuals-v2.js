/**
 * Lookup residual map after base map miss.
 * @param {string} countryKey
 * @param {string} cityKey
 */
export function lookupResidualCityState(countryKey, cityKey) {
  const map = CITY_TO_STATE_RESIDUALS_V2[countryKey];
  if (!map) return null;
  const want = normalizePlaceKey(cityKey);
  if (map[want]) return map[want];
  if (map[cityKey]) return map[cityKey];
  for (const [k, v] of Object.entries(map)) {
    if (normalizePlaceKey(k) === want) return v;
  }
  return null;
}
