function pt({
  name,
  pointType,
  city,
  lat,
  lng,
  submarket,
  source,
  sourceReference,
  dataConfidence = "High",
  notes = "",
  pointSubtype = "",
  address = "",
  hotelDemandRationale = "",
  flagMinor = false,
}) {
  const subNote = `Submarket: ${submarket}.`;
  const flagNote = flagMinor ? " Radar note: regional anchor — verify hotel relevance before scoring." : "";
  return {
    name,
    pointType,
    pointSubtype: pointSubtype || undefined,
    latitude: lat,
    longitude: lng,
    city,
    country: "Puerto Rico",
    region: "Caribbean",
    submarket,
    address: address || undefined,
    source: source || "Public Source",
    sourceReference,
    dataConfidence,
    visibility: "Internal Only",
    includeOnRadarMap: true,
    hotelDemandRationale: hotelDemandRationale || undefined,
    notes: [subNote, notes, flagNote].filter(Boolean).join(" "),
  };
}

