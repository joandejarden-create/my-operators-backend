/**
 * Refresh loyalty.* Brand Explorer presentation rows for all Choice CHI brands.
 * Replaces existing loyalty.* slots (does not touch other tabs or Image attachments).
 *
 *   node scripts/apply-choice-loyalty-presentation-batch.mjs --dry-run
 *   node scripts/apply-choice-loyalty-presentation-batch.mjs
 *   node scripts/apply-choice-loyalty-presentation-batch.mjs --brand "Radisson Blu (Choice)"
 */
import fs from "fs";
import os from "os";
import path from "path";
import { spawnSync } from "child_process";
import { fileURLToPath } from "url";
import "../load-env.js";
import Airtable from "airtable";
import { buildChoicePrivilegesLoyaltyRows } from "./lib/choice-privileges-loyalty-presentation-rows.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const APPLY = path.join(ROOT, "scripts", "apply-brand-explorer-presentation-fixture.mjs");
const BASICS = "Brand Setup - Brand Basics";

function parseArgs(argv) {
  const args = argv.slice(2);
  const i = args.indexOf("--brand");
  return {
    dryRun: args.includes("--dry-run"),
    brandFilter: i >= 0 ? String(args[i + 1] || "").trim() : "",
  };
}

async function listChiBrands(base) {
  const rows = await base(BASICS).select({ maxRecords: 500 }).all();
  return rows
    .filter((r) => String(r.get("Parent Company") || "").includes("Choice Hotels International"))
    .map((r) => String(r.get("Brand Name") || "").trim())
    .filter(Boolean)
    .sort((a, b) => a.localeCompare(b));
}

async function main() {
  const { dryRun, brandFilter } = parseArgs(process.argv);
  const key = process.env.AIRTABLE_API_KEY;
  const baseId = process.env.AIRTABLE_BASE_ID;
  if (!key || !baseId) throw new Error("Set AIRTABLE_API_KEY and AIRTABLE_BASE_ID");

  const base = new Airtable({ apiKey: key }).base(baseId);
  let brands = await listChiBrands(base);
  if (brandFilter) {
    brands = brands.filter((b) => b === brandFilter);
    if (!brands.length) throw new Error(`No CHI Brand Basics row named "${brandFilter}"`);
  }

  console.log(`${dryRun ? "[dry-run] " : ""}Refreshing loyalty.* for ${brands.length} CHI brand(s)…`);

  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), "dc-loyalty-fixture-"));
  let failed = 0;

  try {
    for (const brandName of brands) {
      const fixturePath = path.join(tmpDir, `${brandName.replace(/[^\w.-]+/g, "_")}.json`);
      const payload = {
        targetBrandBasicsName: brandName,
        instructions: "Generated by apply-choice-loyalty-presentation-batch.mjs",
        rows: buildChoicePrivilegesLoyaltyRows(brandName),
      };
      fs.writeFileSync(fixturePath, JSON.stringify(payload, null, 2), "utf8");

      const args = [
        APPLY,
        "--brand-name",
        brandName,
        "--fixture",
        fixturePath,
        "--replace-slot-prefix",
        "loyalty.",
      ];
      if (dryRun) args.push("--dry-run");

      console.log(`\n=== ${brandName} (${payload.rows.length} rows) ===`);
      const r = spawnSync(process.execPath, args, { stdio: "inherit", cwd: ROOT });
      if (r.status !== 0) failed++;
    }
  } finally {
    try {
      fs.rmSync(tmpDir, { recursive: true, force: true });
    } catch {
      /* ignore */
    }
  }

  if (failed) {
    console.error(`\n${failed} brand(s) failed.`);
    process.exit(1);
  }
  console.log(`\nDone: ${brands.length} brand(s) ${dryRun ? "(dry-run)" : "updated"}.`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
