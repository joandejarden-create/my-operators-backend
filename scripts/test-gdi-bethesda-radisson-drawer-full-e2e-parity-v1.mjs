#!/usr/bin/env node
/**
 * Permanent gates for certified drawer commercial content + Tempo presentation.
 *   npm run test:gdi-bethesda-radisson-drawer-full-e2e-parity-v1
 */
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  composeOverviewIdentityLine,
  evaluateCertifiedDrawerCommercialContent,
  appearsTruncatedCustomerProse,
  resolveCoreCommercialBodies,
  resolveContactRelevance,
} from "../lib/group-demand-intelligence/presentation/gdi-certified-drawer-commercial-content-contract-v1.js";
import { createGdiPublicationPackageStore } from "../lib/group-demand-intelligence/publication-package/index.js";
import { attachPackageCustomerPresentation } from "../lib/group-demand-intelligence/publication-package/gdi-package-customer-presentation-attach-v1.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const RADISSON = "recH9h3McgMNFQEla";
const FP =
  "f2bfebc96d75b87b9df5ae239b9e48502e117a4a6c51b344e65375a8a5a87e9d";
const TEMPO = "rx_gdi_s4912_d46e3e911701";

let failed = 0;
function check(name, fn) {
  try {
    fn();
    console.log(`PASS ${name}`);
  } catch (err) {
    failed += 1;
    console.error(`FAIL ${name}: ${err.message}`);
  }
}

check("identity_dedupes_org_prefix", () => {
  const line = composeOverviewIdentityLine({
    organizationName: "Toronto Tempo / WNBA",
    displayTitle:
      "Toronto Tempo / WNBA — 2027 Visiting-Team & Preferred Lodging Development",
  });
  assert.equal(
    line,
    "Toronto Tempo / WNBA — 2027 Visiting-Team & Preferred Lodging Development",
  );
  assert.equal(
    (line.match(/Toronto Tempo \/ WNBA/gi) || []).length,
    1,
  );
});

check("truncation_detector", () => {
  assert.equal(appearsTruncatedCustomerProse("Short complete sentence."), false);
  assert.equal(
    appearsTruncatedCustomerProse(
      "A ".repeat(120) + "mid-size exhibitor, speaker, visiting-team, or overflow lodging near downtown and Exhibition Place. Inference using the supplied hotel specification: a 157-room Harbourfront city hotel is plausible for limited fan, media, spo",
    ),
    true,
  );
});

check("events_projection_fields_present_in_ui", () => {
  const ui = fs.readFileSync(
    path.join(ROOT, "public/js/group-demand-intelligence/dealality-gdi-ui.js"),
    "utf8",
  );
  assert.match(ui, /o\.potentialHotelBusiness/);
  assert.match(ui, /o\.whyActNow/);
  assert.match(ui, /does not include paid contact lookup/);
  assert.match(ui, /gdi-share-mode/);
});

check("cache_bust_updated", () => {
  const auth = fs.readFileSync(
    path.join(ROOT, "public/group-demand-intelligence.html"),
    "utf8",
  );
  const share = fs.readFileSync(
    path.join(ROOT, "public/group-demand-intelligence-share.html"),
    "utf8",
  );
  assert.match(auth, /dealality-gdi-ui\.js\?v=gdi-sortable-list-v1/);
  assert.match(share, /dealality-gdi-ui\.js\?v=gdi-sortable-list-v1/);
});

check("radisson_current_immutable_fingerprint", () => {
  const store = createGdiPublicationPackageStore();
  const cur = store.loadCustomerVisiblePackage(RADISSON);
  assert.equal(cur.ok, true);
  assert.equal(cur.package.contentFingerprintSha256, FP);
});

check("radisson_all_66_evaluate", () => {
  const store = createGdiPublicationPackageStore();
  const cur = store.loadCustomerVisiblePackage(RADISSON);
  const ops = attachPackageCustomerPresentation(cur.package.opportunities || [], {
    hotelId: RADISSON,
  });
  assert.equal(ops.length, 66);
  const rows = ops.map((o) =>
    evaluateCertifiedDrawerCommercialContent(o, { hotelId: RADISSON }),
  );
  assert.equal(rows.length, 66);
  const tempo = ops.find((o) => o.id === TEMPO);
  assert.ok(tempo);
  const bodies = resolveCoreCommercialBodies(tempo);
  assert.ok(bodies.potentialHotelBusiness);
  assert.ok(bodies.whyActNow);
  assert.ok(bodies.recommendedNextStep);
  assert.ok(resolveContactRelevance(tempo));
  const identity = composeOverviewIdentityLine(tempo);
  assert.equal((identity.match(/Toronto Tempo \/ WNBA/gi) || []).length, 1);
});

check("surfe_share_guidance_not_dead_button_only", () => {
  const ui = fs.readFileSync(
    path.join(ROOT, "public/js/group-demand-intelligence/dealality-gdi-ui.js"),
    "utf8",
  );
  // Both Surfe CTA builders must gate on share mode.
  const shareGuards = ui.match(/gdi-share-mode/g) || [];
  assert.ok(shareGuards.length >= 2);
});

check("report_pack_exists_after_audit_script", () => {
  // Soft: pack may be generated by sibling audit script in CI/local.
  const p = path.join(
    ROOT,
    "reports/gdi-bethesda-radisson-drawer-full-e2e-parity-v1/FOUNDER_REPORT.md",
  );
  if (!fs.existsSync(p)) {
    console.log("SKIP report_pack_exists_after_audit_script (run audit script first)");
    return;
  }
  const body = fs.readFileSync(p, "utf8");
  // Historical report may cite prior CURRENT; published CURRENT is FP.
  assert.ok(
    body.includes(FP) ||
      body.includes("533f2642f8c74af881ff525c2335f9a5471f5ef1d04ac16f7646131176f8706d"),
  );
});

if (failed) {
  console.error(`\n${failed} failure(s)`);
  process.exit(1);
}
console.log("\nOK test:gdi-bethesda-radisson-drawer-full-e2e-parity-v1");
