/**
 * @returns {{ amenities: string[], resolveSource: string }}
 */
export function getBrandAdditionalAmenities(brandName, parentCompany = "") {
  const name = String(brandName || "").trim();
  const parent = String(parentCompany || "").trim();

  if (BRAND_AMENITY_OVERRIDES[name]) {
    return {
      amenities: uniq(BRAND_AMENITY_OVERRIDES[name]),
      resolveSource: "brand-override",
    };
  }

  const segKey = PARENT_AMENITY_SEGMENT[parent];
  if (segKey && AMENITY_SEGMENTS[segKey]) {
    return {
      amenities: uniq(AMENITY_SEGMENTS[segKey]),
      resolveSource: `parent:${parent}:${segKey}`,
    };
  }

  return {
    amenities: uniq(AMENITY_SEGMENTS.upperMidscale),
    resolveSource: "default:upperMidscale",
  };
}
