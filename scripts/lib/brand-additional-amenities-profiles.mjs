function uniq(list) {
  const out = [];
  const seen = new Set();
  for (const x of list) {
    if (!x || !ADDITIONAL_AMENITIES_ALLOWED.includes(x) || seen.has(x)) continue;
    if (x === "Not Applicable / None") continue; // never mix NA with real amenities
    seen.add(x);
    out.push(x);
  }
  return out;
}

