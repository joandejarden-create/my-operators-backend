/**
 * Fill missing Brand Explorer presentation rows for all CHI brands (--only-missing).
 *
 *   node scripts/apply-choice-explorer-presentation-gaps-batch.mjs --dry-run
 *   node scripts/apply-choice-explorer-presentation-gaps-batch.mjs
 *   node scripts/apply-choice-explorer-presentation-gaps-batch.mjs --brand "Cambria Hotels"
 */
import fs from "fs";
import os from "os";
import path from "path";
import { spawnSync } from "child_process";
import { fileURLToPath } from "url";
import "../load-env.js";
import Airtable from "airtable";
import { buildCompletePresentationRows } from "./lib/choice-explorer-complete-rows.mjs";
import { resolveChiBrandBasicsName } from "./lib/choice-chi-brand-resolve.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const APPLY = path.join(ROOT, "scripts", "apply-brand-explorer-presentation-fixture.mjs");
const BASICS = "Brand Setup - Brand Basics";

function parseArgs(argv) {
  const args = argv.slice(2);
  const i = args.indexOf("--brand");
  return {
    dryRun: args.includes("--dry-run"),
    brandFilter: i >= 0 ? String(args[i + 1] || "").trim() : "",
  };
}

async function listChiBrands(base) {
  const rows = await base(BASICS).select({ maxRecords: 500 }).all();
  return rows
    .filter((r) => String(r.get("Parent Company") || "").includes("Choice Hotels International"))
    .map((r) => String(r.get("Brand Name") || "").trim())
    .filter(Boolean)
    .sort((a, b) => a.localeCompare(b));
}

async function main() {
  const { dryRun, brandFilter } = parseArgs(process.argv);
  const base = new Airtable({ apiKey: process.env.AIRTABLE_API_KEY }).base(
    process.env.AIRTABLE_BASE_ID
  );
  let brands = await listChiBrands(base);
  if (brandFilter) {
    const resolved = resolveChiBrandBasicsName(brandFilter, brands);
    if (!resolved) throw new Error(`No CHI brand: ${brandFilter}`);
    brands = [resolved];
  }

  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), "dc-explorer-gap-"));
  let failed = 0;

  try {
    for (const brandName of brands) {
      const rows = buildCompletePresentationRows(brandName);
      const fixturePath = path.join(tmpDir, `${brandName.replace(/[^\w.-]+/g, "_")}.json`);
      fs.writeFileSync(
        fixturePath,
        JSON.stringify(
          {
            targetBrandBasicsName: brandName,
            instructions: "Generated by apply-choice-explorer-presentation-gaps-batch.mjs",
            rows,
          },
          null,
          2
        ),
        "utf8"
      );

      const args = [APPLY, "--brand-name", brandName, "--fixture", fixturePath, "--only-missing"];
      if (dryRun) args.push("--dry-run");

      console.log(`\n=== ${brandName} (expected ${rows.length} rows) ===`);
      const r = spawnSync(process.execPath, args, { stdio: "inherit", cwd: ROOT });
      if (r.status !== 0) failed++;
    }
  } finally {
    try {
      fs.rmSync(tmpDir, { recursive: true, force: true });
    } catch {
      /* ignore */
    }
  }

  if (failed) {
    console.error(`\n${failed} brand(s) failed.`);
    process.exit(1);
  }
  console.log(`\nDone: ${brands.length} brand(s) ${dryRun ? "(dry-run)" : "patched (--only-missing)"}.`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
